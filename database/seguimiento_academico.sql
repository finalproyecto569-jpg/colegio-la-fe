DROP DATABASE IF EXISTS seguimiento_academico;
CREATE DATABASE seguimiento_academico CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE seguimiento_academico;

CREATE TABLE usuarios (
    id              INT AUTO_INCREMENT PRIMARY KEY,
    nombre          VARCHAR(80)  NOT NULL,
    documento       VARCHAR(12)  NOT NULL UNIQUE,
    correo          VARCHAR(100) NOT NULL UNIQUE,
    password        VARCHAR(255) NOT NULL,
    rol             ENUM('administrador','coordinador','docente','estudiante') NOT NULL,
    programa        VARCHAR(80)  NULL,
    activo          TINYINT(1)   NOT NULL DEFAULT 1,
    fecha_registro  DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE cursos (
    id          INT AUTO_INCREMENT PRIMARY KEY,
    codigo      VARCHAR(12) NOT NULL UNIQUE,
    nombre      VARCHAR(80) NOT NULL,
    semestre    TINYINT     NOT NULL CHECK (semestre BETWEEN 1 AND 11),
    grupo       VARCHAR(10) NULL,
    periodo     VARCHAR(10) NOT NULL,
    docente_id  INT NULL,
    CONSTRAINT fk_cursos_docente FOREIGN KEY (docente_id) REFERENCES usuarios(id) ON DELETE SET NULL
) ENGINE=InnoDB;

CREATE TABLE matriculas (
    id             INT AUTO_INCREMENT PRIMARY KEY,
    estudiante_id  INT NOT NULL,
    curso_id       INT NOT NULL,
    fecha          DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE KEY uq_matricula (estudiante_id, curso_id),
    CONSTRAINT fk_matriculas_estudiante FOREIGN KEY (estudiante_id) REFERENCES usuarios(id) ON DELETE CASCADE,
    CONSTRAINT fk_matriculas_curso      FOREIGN KEY (curso_id)      REFERENCES cursos(id)   ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE calificaciones (
    id            INT AUTO_INCREMENT PRIMARY KEY,
    matricula_id  INT NOT NULL,
    corte         TINYINT NOT NULL CHECK (corte IN (1,2,3)),
    nota          DECIMAL(2,1) NOT NULL CHECK (nota BETWEEN 0 AND 5),
    fecha         DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE KEY uq_nota (matricula_id, corte),
    CONSTRAINT fk_calificaciones_matricula FOREIGN KEY (matricula_id) REFERENCES matriculas(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE asistencias (
    id            INT AUTO_INCREMENT PRIMARY KEY,
    matricula_id  INT NOT NULL,
    fecha         DATE NOT NULL,
    estado        ENUM('presente','ausente','justificada') NOT NULL,
    UNIQUE KEY uq_asistencia (matricula_id, fecha),
    CONSTRAINT fk_asistencias_matricula FOREIGN KEY (matricula_id) REFERENCES matriculas(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE alertas (
    id                   INT AUTO_INCREMENT PRIMARY KEY,
    estudiante_id        INT NOT NULL,
    curso_id             INT NULL,
    tipo                 ENUM('rendimiento','inasistencia','riesgo','otro') NOT NULL,
    nivel                ENUM('baja','media','alta') NOT NULL,
    descripcion          VARCHAR(500) NOT NULL,
    estado               ENUM('abierta','en_seguimiento','cerrada') NOT NULL DEFAULT 'abierta',
    seguimiento          VARCHAR(500) NULL,
    origen               ENUM('automatica','manual') NOT NULL DEFAULT 'manual',
    creado_por           INT NULL,
    fecha_creacion       DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_actualizacion  DATETIME NULL,
    CONSTRAINT fk_alertas_estudiante FOREIGN KEY (estudiante_id) REFERENCES usuarios(id) ON DELETE CASCADE,
    CONSTRAINT fk_alertas_curso      FOREIGN KEY (curso_id)      REFERENCES cursos(id)   ON DELETE CASCADE,
    CONSTRAINT fk_alertas_creador    FOREIGN KEY (creado_por)    REFERENCES usuarios(id) ON DELETE SET NULL
) ENGINE=InnoDB;

CREATE TABLE anuncios (
    id                 INT AUTO_INCREMENT PRIMARY KEY,
    titulo             VARCHAR(150) NOT NULL,
    descripcion        TEXT NOT NULL,
    fecha_evento       DATE NULL,
    imagen             VARCHAR(255) NULL,
    autor_id           INT NULL,
    fecha_publicacion  DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_anuncios_autor FOREIGN KEY (autor_id) REFERENCES usuarios(id) ON DELETE SET NULL
) ENGINE=InnoDB;

CREATE TABLE grupos (
    id      INT AUTO_INCREMENT PRIMARY KEY,
    nombre  VARCHAR(10) NOT NULL UNIQUE,
    grado   TINYINT NOT NULL CHECK (grado BETWEEN 1 AND 11)
) ENGINE=InnoDB;

